#!/usr/bin/env bash
# Single source of truth for the app version, shared by the GitHub release
# channel and F-Droid.
#
#   versionName   0.<months since Dec 2025>.<dhhmm>
#   versionCode   months * 1000000 + day * 10000 + hhmm
#
# So 2026-11-05 15:01 gives versionName 0.11.51501 and versionCode 11051501.
# Both fit what Android wants: versionCode is a signed 32-bit int capped at
# 2100000000, and this scheme reads 11,051,501 today with room past 2100.
#
# Within a month the code grows with the day and then the clock, and each new
# month adds 1000000, which is more than the largest possible day-and-time
# (312359), so it always increases.
#
# The version is whatever android/version.properties says. Nothing computes a
# version at build time, so a given commit always produces the same numbers.
# That is what F-Droid needs, and it is what makes a release reproducible.
#
# Usage:
#   scripts/version.sh show               read the committed file: "name code"
#   scripts/version.sh write              rewrite the file from the clock (local only)
#   scripts/version.sh print              dry run: what write would produce
#   scripts/version.sh check-tag vX       fail unless the file matches tag vX
#
# Only write changes anything, and it refuses to run under CI.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
FILE="$ROOT/android/version.properties"
EPOCH_YEAR=2025
EPOCH_MONTH=12

compute() {
    local y m d hh mm months dhhmm name code
    y=$(date -u +%Y)
    m=$(date -u +%m)
    d=$(date -u +%d)
    hh=$(date -u +%H)
    mm=$(date -u +%M)
    months=$(( (10#$y - EPOCH_YEAR) * 12 + 10#$m - EPOCH_MONTH ))
    dhhmm=$(( 10#$d * 10000 + 10#$hh * 100 + 10#$mm ))
    name="0.${months}.${dhhmm}"
    code=$(( months * 1000000 + dhhmm ))
    printf '%s %s\n' "$name" "$code"
}

read_file() {
    local name code
    name=$(sed -n 's/^VERSION_NAME=//p' "$FILE")
    code=$(sed -n 's/^VERSION_CODE=//p' "$FILE")
    if [ -z "$name" ] || [ -z "$code" ]; then
        echo "version.sh: $FILE is missing VERSION_NAME or VERSION_CODE" >&2
        exit 1
    fi
    printf '%s %s\n' "$name" "$code"
}

case "${1:-print}" in
    print)
        compute
        ;;
    write)
        if [ -n "${CI:-}" ]; then
            echo "version.sh: write is local only, because a version committed from CI" >&2
            echo "would make one commit build differently depending on when it ran." >&2
            echo "Run it yourself, then commit the file." >&2
            exit 1
        fi
        read -r name code <<<"$(compute)"
        {
            echo "# Generated by scripts/version.sh write. Committed on purpose:"
            echo "# F-Droid builds this file, so a clean checkout must carry it."
            echo "VERSION_NAME=$name"
            echo "VERSION_CODE=$code"
        } > "$FILE"
        printf '%s %s\n' "$name" "$code"
        ;;
    show)
        read_file
        ;;
    check-tag)
        tag=${2:?usage: version.sh check-tag vX.Y.Z}
        read -r name _code <<<"$(read_file)"
        if [ "v$name" != "$tag" ]; then
            echo "version.sh: tag $tag does not match VERSION_NAME=$name in $FILE" >&2
            echo "run scripts/version.sh write, commit, then tag again" >&2
            exit 1
        fi
        echo "tag $tag matches $FILE"
        ;;
    *)
        echo "usage: version.sh {print|write|show|check-tag vX}" >&2
        exit 2
        ;;
esac
